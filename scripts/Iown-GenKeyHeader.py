#!/usr/bin/env python3
"""
Generate include/iown_key.h from a 1W controller QR code (e.g. Somfy Situo).

The QR payload is read from a file. The decrypted key is written only into the
generated header (which is git-ignored) and is never printed to the terminal.

Usage: Iown-GenKeyHeader.py <qr payload file> <output header path> [node id hex]

  node id hex: optional source address override (e.g. b51a40 for a non-default
               channel). Defaults to the address embedded in the QR payload.
"""

import sys

import ioCrypto


def parse_qr(path):
  raw = open(path).read()
  qr = "".join(c for c in raw if c in "0123456789abcdefABCDEF")
  if len(qr) != 56:
    sys.exit(f"QR payload: expected 56 hex chars, got {len(qr)}")
  return bytes.fromhex(qr[2:8]), bytes.fromhex(qr[8:40])


def main(args):
  if len(args) not in (3, 4):
    sys.exit(__doc__)
  qr_node, product_key = parse_qr(args[1])
  node = bytes.fromhex(args[3]) if len(args) == 4 else qr_node
  if len(node) != 3:
    sys.exit("node id must be 3 bytes")
  key = bytes(ioCrypto.encrypt_1W_key(node, product_key)) # decrypt with public transfer key

  def c_array(b):
    return "{ " + ", ".join(f"0x{x:02X}" for x in b) + " }"

  header = f"""// GENERATED by scripts/Iown-GenKeyHeader.py - DO NOT COMMIT (git-ignored)
// 1W controller key and node ID for this installation.
#pragma once

#define IOWN_NODE_ID   {c_array(node)}       // {len(node)} bytes, frame order
#define IOWN_KEY       {c_array(key)} // {len(key)} bytes
"""
  with open(args[2], "w") as f:
    f.write(header)
  print(f"wrote {args[2]} (node {node.hex()}, key not shown)")


if __name__ == "__main__":
  main(sys.argv)
